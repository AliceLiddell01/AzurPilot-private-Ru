"""Иерархия исключений.

Определяет все пользовательские исключения AzurPilot. По тяжести и возможности
восстановления исключения разделены на следующие группы:

Нормальное завершение кампании (ожидаемое окончание сценария):
    - CampaignEnd: кампания завершена штатно (возврат к выбору этапа)
    - OilExhausted: нефть закончилась, дальнейший выход невозможен
    - OilMaxed: запас нефти достиг максимума, её нужно расходовать

Ошибки навигации по карте (восстанавливаемые, вызывают повторную попытку):
    - MapDetectionError: не удалось распознать перспективу карты (ошибка сетки)
    - MapWalkError: ошибка перемещения флота (цель недостижима)
    - MapEnemyMoved: противник переместился, маршрут нужно построить заново
    - CampaignNameError: название этапа не удалось распознать

Ошибки состояния игры (вызывают перезапуск эмулятора):
    - GameStuckError: игра зависла (нет полезных действий в течение 1 минуты,
      во время боя — 5 минут)
    - GameBugError: ошибка клиента игры (обычно помогает перезапуск)
    - GameTooManyClickError: слишком много нажатий (одна кнопка нажата не менее
      12 раз за последние 15 действий)

Ошибки подключения и страницы (вызывают перезапуск или ручное вмешательство):
    - GameNotRunningError: игра не запущена
    - GamePageUnknownError: текущую страницу не удалось распознать
    - EmulatorNotRunningError: эмулятор не запущен

Ошибки разработчика и скрипта:
    - ScriptError: ошибка логики скрипта (обычно программная ошибка)
    - TemplateMatchError: базовая ошибка подготовки или выполнения шаблонного
      поиска с исходной причиной OpenCV в цепочке исключений
    - OpsiMapDetectionError: предметная ошибка распознавания карты Operation
      Siren с сохранением ScriptError recovery-контракта
    - OpsiStorageError: предметная ошибка обработки хранилища Operation Siren
    - ScriptEnd: штатное завершение скрипта (для прерывания текущего сценария)

Невосстанавливаемые ошибки (требуют ручного вмешательства):
    - RequestHumanTakeover: требуется ручное вмешательство (например, из-за
      серьёзной ошибки конфигурации)
    - AutoSearchSetError: не удалось настроить автоматический поиск
    - HardNotSatisfied: не выполнены предварительные условия сложного режима
"""


class CampaignEnd(Exception):
    """Штатное завершение кампании.

    Выбрасывается, когда флот возвращается к выбору этапа. Цикл планировщика
    перехватывает исключение и выполняет дальнейшую логику, например переход
    к следующему этапу или сохранение данных о добыче.
    """
    pass


class OilExhausted(Exception):
    """Нефть закончилась.

    Выбрасывается, когда на экране подготовки к бою обнаружено недостаточное
    количество нефти; текущая задача кампании завершается.
    """
    pass


class OilMaxed(Exception):
    """Запас нефти достиг максимума.

    Выбрасывается при переполнении запаса и сообщает, что нефть нужно расходовать,
    чтобы избежать потерь.
    """
    pass


class MapDetectionError(Exception):
    """Не удалось распознать перспективу карты.

    Выбрасывается, когда по скриншоту невозможно корректно разобрать сетку карты.
    Возможные причины: перекрытие информационной панелью, окно поверх игры или
    некорректное изображение.
    """
    pass


class MapWalkError(Exception):
    """Ошибка перемещения флота.

    Выбрасывается, когда флот не может достичь целевой клетки; возможные причины —
    заблокированный маршрут, нехватка ходов и тому подобное.
    """
    pass


class MapEnemyMoved(Exception):
    """Противник переместился, и маршрут стал недействителен.

    В системе с подвижными противниками после их хода текущий маршрут может
    перестать быть актуальным, поэтому его нужно построить заново. Исключение
    прерывает текущее перемещение и запускает повторный поиск пути.
    """
    pass


class CampaignNameError(Exception):
    """Название этапа не удалось распознать.

    Выбрасывается, когда название этапа из конфигурации невозможно сопоставить
    с существующим файлом карты.
    """
    pass


class ScriptError(Exception):
    """Ошибка логики скрипта.

    Обычно это программная ошибка, но иногда причина может быть случайной.
    Вызывает попытку восстановиться через перезапуск эмулятора.
    """
    pass


class TemplateMatchError(ScriptError):
    """Базовая ошибка подготовки или выполнения шаблонного поиска."""
    pass


class OpsiError(ScriptError):
    """Предметная ошибка Operation Siren с прежним recovery-контрактом ScriptError."""
    pass


class OpsiStorageError(OpsiError):
    """Ошибка распознавания или обработки предмета в хранилище Operation Siren."""
    pass


class OpsiStorageTemplateMatchError(OpsiStorageError):
    """Ошибка шаблонного поиска предмета в хранилище Operation Siren."""
    pass


class OpsiMapDetectionError(OpsiError):
    """Ошибка распознавания карты Operation Siren."""
    pass


class OpsiMapDetectionTemplateMatchError(OpsiMapDetectionError):
    """Ошибка шаблонного поиска при распознавании карты Operation Siren."""
    pass


class ScriptEnd(Exception):
    """Штатное завершение скрипта.

    Используется для прерывания текущего сценария, например при необходимости
    отложить задачу из-за низкой мотивации. Ошибкой не считается и в число сбоев
    не включается.
    """
    pass


class GameStuckError(Exception):
    """Игра зависла.

    Срабатывает, если в течение 1 минуты нет полезных действий со скриншотами
    (во время боя или запуска — в течение 5 минут). Обычно помогает перезапуск
    эмулятора.
    """
    pass


class ResearchRewardError(GameStuckError):
    """Ошибка управляемого жизненного цикла награды исследования."""
    pass


class ResearchRewardPopupTimeoutError(ResearchRewardError):
    """Окно награды исследования не стабилизировалось в установленный срок."""
    pass


class ResearchRewardReturnTimeoutError(ResearchRewardError):
    """После сохранения награды не подтверждён устойчивый экран исследования."""
    pass


class GameBugError(Exception):
    """В клиенте игры произошла ошибка, которую AzurPilot не может обработать.

    Обычно восстановление выполняется перезапуском игры.
    """
    pass


class GameTooManyClickError(Exception):
    """Слишком много нажатий; вероятно, выполнение зациклилось.

    Срабатывает, если одна кнопка нажата не менее 12 раз за последние 15 действий
    или две кнопки нажаты не менее 6 раз каждая.
    """
    pass


class ResearchProjectStartError(GameTooManyClickError):
    """Исследовательский проект не удалось запустить после ограниченных попыток."""
    pass


class ResearchQueueStateError(GameBugError):
    """Состояние очереди исследования противоречит ожидаемому игровому контракту."""
    pass


class EmulatorNotRunningError(Exception):
    """Эмулятор не запущен.

    Выбрасывается, когда подключение ADB не удалось и процесс эмулятора отсутствует.
    """
    pass


class GameNotRunningError(Exception):
    """Игра не запущена.

    Выбрасывается, когда скриншот чёрный или процесс игры завершился.
    """
    pass


class GamePageUnknownError(Exception):
    """Текущую страницу игры не удалось распознать.

    Выбрасывается, когда логика определения страницы не находит ни одного
    известного соответствия.
    """
    pass


class RequestHumanTakeover(Exception):
    """Требуется ручное вмешательство.

    AzurPilot не может обработать такую ошибку; возможная причина — неверная
    конфигурация. Пользователю нужно вручную проверить и исправить проблему.
    """
    pass


class AutoSearchSetError(Exception):
    """Не удалось настроить автоматический поиск.

    Выбрасывается, когда параметры автоматического поиска невозможно корректно
    установить, например из-за ошибки на экране подготовки флота.
    """
    pass


class HardNotSatisfied(RequestHumanTakeover):
    """Не выполнены предварительные условия сложного режима.

    Наследуется от RequestHumanTakeover и выбрасывается, когда для сложного
    этапа не выполнены необходимые условия.
    """
    pass
