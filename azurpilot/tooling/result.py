    """Категории завершения CLI."""

    SUCCESS = 0
    INVOCATION = 2
    PRECONDITION = 20
    OWNERSHIP_CONFLICT = 21
    TIMEOUT = 22
    DEPENDENCY_UNAVAILABLE = 23
    ROLLED_BACK = 24
    ROLLBACK_UNKNOWN = 25
    UNEXPECTED = 30


